window.RTL_LANGS = ["ar", "fa"];

// Detect user's language from localStorage > URL ?lang= > browser > default 'en'
window.detectLang = function () {
  const stored = localStorage.getItem("wc_lang");
  if (stored && window.I18N[stored]) return stored;

  const urlLang = new URLSearchParams(window.location.search).get("lang");
  if (urlLang && window.I18N[urlLang]) return urlLang;

  const browser = (navigator.language || "en").toLowerCase();
  // Handle Chinese variants
  if (browser.startsWith("zh-tw") || browser.startsWith("zh-hk") || browser.includes("hant")) {
    return "zh-TW";
  }
  if (browser.startsWith("zh")) return "zh-CN";
  const short = browser.split("-")[0];
  if (window.I18N[short]) return short;
  return "en";
};

window.setLang = function (code) {
  if (!window.I18N[code]) return;
  localStorage.setItem("wc_lang", code);
  document.documentElement.lang = code;
  document.documentElement.dir = window.RTL_LANGS.includes(code) ? "rtl" : "ltr";
  applyTranslations(code);
};

window.t = function (key, lang) {
  lang = lang || window.detectLang();
  return (window.I18N[lang] && window.I18N[lang][key]) || window.I18N.en[key] || key;
};

window.applyTranslations = function (lang) {
  lang = lang || window.detectLang();
  document.documentElement.lang = lang;
  document.documentElement.dir = window.RTL_LANGS.includes(lang) ? "rtl" : "ltr";

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    el.textContent = window.t(key, lang);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    el.setAttribute("placeholder", window.t(key, lang));
  });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    const key = el.getAttribute("data-i18n-title");
    el.setAttribute("title", window.t(key, lang));
  });
  if (document.querySelector("[data-i18n-doc-title]")) {
    document.title = window.t("site_title", lang);
  }
  document.dispatchEvent(new CustomEvent("langchange", { detail: { lang } }));
};

